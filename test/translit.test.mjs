// Checks the Tamil -> Thanglish caption converter on common words (built from code points, file stays ASCII).
import { toThanglish } from '../public/translit.js';
const T = (...cps) => String.fromCodePoint(...cps);
const cases = [
  [T(0x0B8E, 0x0BA9, 0x0BCD, 0x0BA9), 'enna'],
  [T(0x0B8E, 0x0BAA, 0x0BCD, 0x0BAA, 0x0B9F, 0x0BBF), 'eppadi'],
  [T(0x0BA8, 0x0BBE, 0x0BA9, 0x0BCD), 'naan'],
  [T(0x0BAA, 0x0BC7, 0x0B9A, 0x0BC1), 'pesu'],
  [T(0x0BB5, 0x0BA8, 0x0BCD, 0x0BA4, 0x0BBE, 0x0BA9, 0x0BCD), 'vandhaan'],
  [T(0x0BA4, 0x0B99, 0x0BCD, 0x0B95, 0x0BAE, 0x0BCD), 'thangam'],
  [T(0x0BAE, 0x0B9E, 0x0BCD, 0x0B9A, 0x0BB3, 0x0BCD), 'manjal'],
  [T(0x0BB5, 0x0BA3, 0x0BCD, 0x0B9F, 0x0BBF), 'vandi'],
  [T(0x0B92, 0x0BA9, 0x0BCD, 0x0BB1, 0x0BC1), 'ondru'],
  [T(0x0B95, 0x0BBE, 0x0BB1, 0x0BCD, 0x0BB1, 0x0BC1), 'kaatru'],
  [T(0x0BB5, 0x0BC6, 0x0B9A, 0x0BCD, 0x0B9A, 0x0BC1), 'vechu'],
  [T(0x0B95, 0x0BA4, 0x0BCD, 0x0BA4, 0x0BC1, 0x0B95, 0x0BCD, 0x0B95), 'kathukka'],
  [T(0x0B87, 0x0BA4, 0x0BC1), 'idhu'],
  [T(0x0B9A, 0x0BCA, 0x0BB2, 0x0BCD, 0x0BB2, 0x0BC1, 0x0B99, 0x0BCD, 0x0B95), 'sollunga'],
  [T(0x0BAA, 0x0BC1, 0x0BB0, 0x0BBF, 0x0BAF, 0x0BB2), 'puriyala'],
  [T(0x0BB0, 0x0BCA, 0x0BAE, 0x0BCD, 0x0BAA), 'romba'],
  [T(0x0BA4, 0x0BAE, 0x0BBF, 0x0BB4, 0x0BCD), 'thamizh'],
  [`Hi ${T(0x0BA8, 0x0BBE, 0x0BA9, 0x0BCD)} OK`, 'Hi naan OK'],
];
let bad = 0;
for (const [src, want] of cases) {
  const got = toThanglish(src);
  if (got !== want) { bad++; console.log('MISMATCH', JSON.stringify(got), 'want', want); }
}
console.log(`translit: ${cases.length - bad}/${cases.length} ok`);
process.exit(bad ? 1 : 0);
